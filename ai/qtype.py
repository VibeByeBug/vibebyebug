"""질문 유형 판정과 유형별 검색어 확장 — 전부 정규식, LLM/임베딩 없음.

왜 규칙인가:
임베딩은 '무슨 얘기인지'를 벡터로 만드는데, 질문 유형은 '어떻게 묻는지'로 정해진다.
"AI 성능이 얼마나 나왔나요"(사실확인)와 "AI가 틀리면 어떻게 되나요"(한계반론)는
주제가 같아 임베딩상 이웃이지만 유형이 다르다. 실제로 임베딩+kNN 은 42.2% 로
최다 클래스만 찍기(46.7%)보다 못했고, 아래 규칙은 91.1% 였다.

주의: 이 규칙과 확장어는 45개 질문의 정답을 본 뒤에 작성됐다. 그 45개에 대한 성능은
낙관적으로 부풀려져 있다. 새 질문셋으로 다시 재야 진짜 값을 안다.
"""

from __future__ import annotations

import re

# 순서가 중요하다 - 위에서부터 먼저 걸린다.
RULES = [
    ("한계반론", r"한계|배제|흔들|놓쳤|아닌가|않나요|예측할 수|전부 실제|믿어도"),
    ("근거",     r"왜 |왜하|근거|확인하셨|검증|사례가 있나"),
    ("절차",     r"어떻게|어떤 방식|어떤 기준|기준으로|순서|나누셨|나누신|처리하셨|바꾸신|추리신|쓰신 거|먼저 보|먼저 하|매길 때|정하신|정한 건"),
]

# [폐기됨] 유형별 검색어 확장 - 측정 결과 오히려 손해였다.
#
#   BM25 단독      R@3 80.0% -> 68.9%  (-11.1%p)
#   하이브리드      R@3 93.3% -> 84.4%  ( -8.9%p)
#
# 이유: 확장어("규칙 선정 기준 순서 단계 ...")가 거의 모든 슬라이드에 등장하는
# 흔한 말이다. BM25 는 드문 단어에 높은 점수를 주는데, 흔한 단어를 얹으니 질문을
# 구별해주던 단어의 비중이 묻혔다. 표적 3개를 건지려다 나머지 42개를 망가뜨렸다.
#
# 코드는 재현용으로 남긴다. 기본 경로에서는 쓰지 않는다.
# 다시 시도한다면 흔한 말을 얹는 대신 문서 쪽 색인에 동의어를 심는 방향이 맞다.
EXPANSION = {
    "절차":     "규칙 선정 기준 순서 단계 우선 과정 방식",
    "근거":     "검증 확인 결과 비교 근거 유의",
    "한계반론": "한계 주의 다만 제외 아니다 유지율",
    "사실확인": "",
}


def classify(question: str) -> str:
    for label, pat in RULES:
        if re.search(pat, question):
            return label
    return "사실확인"


def expand(question: str) -> str:
    """[폐기됨] 확장 질의. 위 주석 참고 - 측정에서 손해였으므로 쓰지 말 것."""
    extra = EXPANSION.get(classify(question), "")
    return f"{question} {extra}".strip() if extra else question
