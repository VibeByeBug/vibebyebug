// 말로 받은 질문에서 군말을 걷어낸다. 화면에 띄우는 질문과 서버로 보내는 질문 모두 이 글을 쓴다.
// AI 를 부르지 않는다: 규칙으로 1ms 안에 끝나야 응답 목표(발화 종료 후 1초)를 지킨다.
// 뜻이 있을 수 있는 말(그 모델, 저 부분, 이제)은 남기고, 혼자 떨어진 소리와 인사말만 뺀다.

// 혼자 떨어져 나온 소리. "어..", "음~", "으음" 처럼 늘인 것도 포함한다
const FILLER_WORDS = [
  '어+',
  '음+',
  '으+음+',
  '흠+',
  '엄+',
  '아+',
  '에+',
  '에헤',
  '그러니까요?',
  '뭐랄까요?',
  '뭐지',
  '뭐냐면',
  '있잖아요?',
  '저기요',
];
const EDGE = '(^|[\\s,.?!…~])';
const AFTER = '[.…~,]*(?=$|[\\s,.?!…])';
const FILLER = new RegExp(`${EDGE}(?:${FILLER_WORDS.join('|')})${AFTER}`, 'g');

// "그...", "저," 처럼 말끝을 흐린 지시어. 쉼표나 말줄임이 붙었을 때만 뺀다 ("그 모델" 은 남긴다)
const TRAILING_DEMONSTRATIVE = /(^|\s)(?:그|저|이|요)[.…~,]+(?=\s|$)/g;

// 인사말과 질문 머리말. 검색에는 방해만 된다
const COURTESY = [
  /안녕하세요[.,!]*/g,
  /(?:발표|설명)\s*(?:정말|아주|너무|진짜)?\s*잘\s*들었습니다[.,!]*/g,
  /(?:좋은\s*)?발표\s*감사합니다[.,!]*/g,
  /수고\s*많?으?셨습니다[.,!]*/g,
  /질문\s*(?:하나|한\s*가지|몇\s*가지)?\s*(?:드려도\s*될까요|드리겠습니다|드릴게요|드립니다|있습니다|있는데요|할게요|하겠습니다)[.,?]*/g,
  /궁금한\s*(?:게|점이|것이|부분이)\s*(?:하나|좀)?\s*있는데요?[.,]*/g,
];

export function cleanQuestion(raw: string): string {
  let s = ` ${raw.replace(/\s+/g, ' ')} `;
  for (const re of COURTESY) s = s.replace(re, ' ');
  // 군말은 붙어서 여러 번 나오므로 ("어 음 그러니까") 더 뺄 게 없을 때까지 돌린다
  for (let i = 0; i < 4; i++) {
    const before = s;
    s = s.replace(FILLER, '$1').replace(TRAILING_DEMONSTRATIVE, '$1');
    if (s === before) break;
  }
  // 말을 더듬어 같은 낱말을 되풀이한 것 ("그 그 모델", "가격 가격은" 은 두 번째가 달라서 남는다)
  s = s.replace(/(^|\s)(\S{1,4})(?:\s+\2)+(?=\s|$)/g, '$1$2');
  return s
    .replace(/\s+([,.?!])/g, '$1') // 빼고 남은 문장부호 앞 빈칸
    .replace(/([,.])(?:\s*[,.])+/g, '$1') // 겹친 쉼표, 마침표
    .replace(/\s+/g, ' ')
    .replace(/^[\s,.…~]+/, '') // 앞에 남은 쉼표
    .trim();
}
